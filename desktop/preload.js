const { contextBridge, ipcRenderer } = require('electron');
const call = (ch, ...a) => ipcRenderer.invoke(ch, ...a);
const on = ch => cb => { const f = (_e, v) => cb(v); ipcRenderer.on(ch, f); return () => ipcRenderer.removeListener(ch, f); };
contextBridge.exposeInMainWorld('glint', {
  state: () => call('state'),
  setSettings: p => call('settings:set', p),
  onSettings: fn => ipcRenderer.on('glint:settings', (_, s) => fn(s)),
  mics: () => call('mics'),
  pickFolder: () => call('pickFolder'),
  openClipsDir: () => call('openClipsDir'),
  openExternal: u => call('openExternal', u),
  clipNow: () => call('clipNow'),
  audioApps: { add: a => call('audioApps:add', a), remove: id => call('audioApps:remove', id) },
  storageUsage: () => call('storage:usage'),
  highlightSeen: () => call('highlight:seen'),
  pickCustomSound: () => call('sound:pickCustom'),
  library: {
    list: () => call('library:list'),
    update: (id, p) => call('library:update', id, p),
    remove: (id, deleteFile) => call('library:delete', id, deleteFile),
    reveal: id => call('library:reveal', id),
    strip: id => call('library:strip', id),
    thumb: id => call('library:thumb', id),
    tracks: id => call('library:tracks', id),
  },
  exportClip: (id, kind) => call('export', id, kind),
  upload: {
    start: (id, o) => call('upload:start', id, o),
    cancel: id => call('upload:cancel', id),
    patch: (id, p) => call('upload:patch', id, p),
    remove: id => call('upload:delete', id),
    publish: (id, o) => call('upload:publish', id, o),
    estimate: (id, o) => call('upload:estimate', id, o),
  },
  account: {
    signIn: () => call('account:signIn'),
    cancel: () => call('account:cancel'),
    signOut: () => call('account:signOut'),
    refresh: () => call('account:refresh'),
  },
  games: {
    list: () => call('games:list'),
    running: (refresh, mode) => call('games:running', refresh, mode),
    add: g => call('games:add', g),
    pickExe: () => call('games:pickExe'),
    update: (id, p) => call('games:update', id, p),
    remove: id => call('games:remove', id),
  },
  update: { check: () => call('update:check'), install: () => call('update:install') },
  win: cmd => call('win', cmd),
  onStatus: on('glint:status'),
  onLibrary: on('glint:library'),
  onUpload: on('glint:upload'),
  onAccount: on('glint:account'),
  onUpdate: on('glint:update'),
  onNotice: on('glint:notice'),
  onWin: on('glint:win'),
  onHighlight: on('glint:highlight'),
});
